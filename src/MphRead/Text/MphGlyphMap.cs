    private static readonly Dictionary<int, ushort> Codes = Build();
    private static Dictionary<int, ushort> Build()
    {
        var result = new Dictionary<int, ushort>();
        for (ushort i = 32; i <= 126; i++) result[i] = i;
        for (int i = 0; i < Extended.Count; i++)
            if (Extended[i].Length == 1 && Extended[i][0] != ' ')
                result.TryAdd(Extended[i][0], (ushort)(128 + i));
        return result;
    }
    internal static bool TryMap(Rune rune, out ushort glyph) => Codes.TryGetValue(rune.Value, out glyph);
    internal static string? Unicode(int glyph) => glyph is >= 32 and <= 126 ? ((char)glyph).ToString()
        : glyph >= 128 && glyph - 128 < Extended.Count && Extended[glyph - 128].Length == 1
            && Extended[glyph - 128] != " " ? Extended[glyph - 128] : null;
