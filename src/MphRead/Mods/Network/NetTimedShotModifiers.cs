using System;
using MphRead.Entities;

namespace MphRead.Mods.Network;

internal readonly record struct TimedShotModifierDecision(bool Applied, bool Double,
    bool Prime, bool Affinity, bool BaseFallback);

// This policy owns timed modifiers, not legacy geometry admission. The exact
// authored FireEvent remains presentation evidence and is never rewritten.
internal static class NetTimedShotModifiers
{
    internal static long Trusted, BaseFallback, ShadowOnly, ClaimBounded, ClaimUnavailable, HeadFallback;
    internal static bool Enforcing => NetTimedShotProof.Mode == TimedGrantProofMode.Enforce
        && NetSession.Active && NetSession.IsAuthority;
    internal static bool Ordinary(byte weapon) => weapon <= (byte)BeamType.OmegaCannon
        && weapon != (byte)BeamType.Judicator && weapon != (byte)BeamType.ShockCoil
            && weapon != (byte)BeamType.OmegaCannon;

    internal static TimedShotModifierDecision Resolve(TimedShotCertificate? attempt, PlayerEntity player)
    {
        if (!Enforcing || !NetTimedShotProof.Eligible(player)) return default;
        if (attempt is not { } shot || !Ordinary(shot.Fire.Weapon)
            || shot.Unavailable == TimedShotUnavailable.Unsupported)
        { ShadowOnly++; return default; }
        bool known = NetShotSourceJournal.TryState(shot.Key, shot.Fire.SourceFrame, out var source);
        // Native input is generated by this authority. A missing remote frame
        // retains the intrinsic row only for the exact current authority life;
        // forwarded affinity/Prime hints never substitute for retained facts.
        bool native = shot.Lane == TimedShotSource.NativeInput;
        bool prime = known ? source.Prime : native && player.IsPrimeHunter;
        var hunter = known ? source.Hunter : player.Hunter;
        bool sameLife = (shot.Key with { ShotId = 0 }) == ShotKey.For(player.SlotIndex, 0);
        bool affinity = known || native || sameLife
            ? prime || Weapons.GetAffinityBeam(hunter) == (BeamType)shot.Fire.Weapon : false;
        bool fallback = shot.Knowledge == TimedGrantKnowledge.Unavailable || !shot.TrustedSource;
        if (fallback) BaseFallback++; else Trusted++;
        return new(true, shot.AuthorizedDouble, prime, affinity, fallback);
    }

    internal static void Reset()
        => Trusted = BaseFallback = ShadowOnly = ClaimBounded = ClaimUnavailable = HeadFallback = 0;

    internal static object Capture() => new { Policy = NetTimedShotProof.Mode.ToString(),
        Enforcing, Trusted, BaseFallback, ShadowOnly, ClaimBounded, ClaimUnavailable, HeadFallback };

    internal static bool TryClaimLimit(int slot, in HitClaimPacket claim,
        TimedVictimDamageProfile? retainedProfile, out uint limit)
        => TryClaimLimit(slot, claim, retainedProfile, out limit, out _);

    internal static bool TryClaimLimit(int slot, in HitClaimPacket claim,
        TimedVictimDamageProfile? retainedProfile, out uint limit, out bool headshot,
        TimedImperialistImpact? retainedImpact = null)
    {
        limit = ushort.MaxValue;
        headshot = (claim.Flags & HitClaimPacket.FlagHeadshot) != 0;
        if (!Enforcing || !Ordinary(claim.Beam)) return true;
        var key = NetShotProof.Key(slot, claim);
        if (!NetTimedShotProof.TryGet(key, out var shot) || !shot.Damage.Present
            || shot.Fire.Weapon != claim.Beam || shot.Fire.AckFrame != claim.LaunchFrame
            || claim.ComponentId == 0 || claim.ComponentId > shot.Components
            || !float.IsFinite(claim.HitPoint.X) || !float.IsFinite(claim.HitPoint.Y)
            || !float.IsFinite(claim.HitPoint.Z)) { ClaimUnavailable++; return false; }
        // Missing head geometry does not discard an otherwise admitted body
        // hit. Its actual body channel retains ordinary damage, without the
        // head amount, armour bypass, or headshot feedback.
        TimedImperialistImpact? exact = null;
        if (claim.Beam == (byte)BeamType.Imperialist)
        {
            if (retainedImpact is { Valid: true } frozenImpact && frozenImpact.Payment == NetShotProof.PaymentKey(slot, claim)
                && shot.Damage.FirstSegmentKnown && frozenImpact.Frame == shot.Damage.FirstCollisionFrame
                && frozenImpact.NativeChannel <= int.MaxValue)
                exact = frozenImpact;
            else if (NetTimedImperialistImpact.TryResolve(shot, claim, out var resolved)) exact = resolved;
            if (headshot && (exact is not { } known || !known.NativeHead))
            { headshot = false; HeadFallback++; }
        }
        else if (headshot && NetShotProof.ValidateTimedHead(claim, shot) != ShotProofReason.Verified)
        { headshot = false; HeadFallback++; }
        const byte effects = HitClaimPacket.FlagFrozen | HitClaimPacket.FlagBurning | HitClaimPacket.FlagDisrupted;
        bool direct = (claim.Flags & HitClaimPacket.FlagDirect) != 0;
        byte allowedEffects = shot.Damage.EffectsFor(direct);
        if ((claim.Flags & effects & ~allowedEffects) != 0) return false;
        TimedVictimDamageProfile profile;
        uint profileFrame = exact?.Frame ?? claim.AckFrame;
        if (retainedProfile is { } retained && (exact == null || retained.EffectFrame == profileFrame)) profile = retained;
        else if (!NetTimedDamageProfile.TryGet(claim.VictimSlot, claim.VictimGeneration,
            claim.VictimLifeId, profileFrame, out profile)) { ClaimUnavailable++; return false; }
        if (profile.Key.AuthorityEpoch != key.AuthorityEpoch || profile.Key.MatchId != key.MatchId
            || profile.Key.ShooterSlot != claim.VictimSlot || profile.Key.Generation != claim.VictimGeneration
            || profile.Key.LifeId != claim.VictimLifeId) return false;
        var boundedClaim = claim;
        if (!headshot) boundedClaim.Flags &= unchecked((byte)~HitClaimPacket.FlagHeadshot);
        float channel = shot.Damage.Channel(boundedClaim, out bool nativeHead);
        if (exact is { } impact) { channel = impact.NativeChannel; nativeHead = impact.NativeHead; }
        if (!float.IsFinite(channel) || channel < 0 || channel > int.MaxValue) return false;
        limit = profile.CompleteDamage(channel, (BeamType)claim.Beam, nativeHead, claim.VictimSlot == slot);
        headshot &= nativeHead;
        ClaimBounded++;
        return true;
    }
}
