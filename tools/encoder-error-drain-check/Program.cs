using System.Text;
using MphRead.Mods.Replay;

int passed = 0, failed = 0;
async Task Check(string name, Func<Task> test)
{
    try { await test(); passed++; Console.WriteLine("PASS " + name); }
    catch (Exception ex) { failed++; Console.WriteLine($"FAIL {name}: {ex.Message}"); }
}
void Require(bool value) { if (!value) throw new InvalidOperationException("contract failed"); }
await Check("empty stderr consumed without taking reader ownership", async () => {
    using var source = new MemoryStream(); using var reader = new StreamReader(source, leaveOpen: true);
    await ReplayEncoderErrorDrain.Drain(reader); Require(reader.Peek() == -1 && source.CanRead);
});
await Check("fragmented Unicode stderr and EOF consumed exactly", async () => {
    byte[] bytes = Encoding.UTF8.GetBytes("Encoder banner\r\n\u03bb\u96ea\ud83c\udfb5\ntrailing unterminated text");
    using var source = new FragmentedStream(bytes); using var reader = new StreamReader(source, leaveOpen: true);
    await ReplayEncoderErrorDrain.Drain(reader); Require(source.Consumed == bytes.Length && reader.Peek() == -1 && source.CanRead);
});
await Check("large no-newline stderr is drained with bounded allocation", async () => {
    using (var warm = new StreamReader(new GeneratedStream(4096))) await ReplayEncoderErrorDrain.Drain(warm);
    using var source = new GeneratedStream(16 * 1024 * 1024); using var reader = new StreamReader(source);
    long before = GC.GetTotalAllocatedBytes(precise: true);
    await ReplayEncoderErrorDrain.Drain(reader);
    long allocated = GC.GetTotalAllocatedBytes(precise: true) - before;
    Console.WriteLine($"allocation witness: {source.Consumed} generated bytes, {allocated} allocated bytes");
    Require(source.Consumed == 16 * 1024 * 1024 && reader.Peek() == -1);
    Require(allocated < 1024 * 1024); // Test threshold, never an output/content rejection limit.
});
await Check("mid-read I/O failure propagates to existing probe fallback", async () => {
    using var source = new GeneratedStream(8192, failAfter: 1024); using var reader = new StreamReader(source);
    bool failedRead = false;
    try { await ReplayEncoderErrorDrain.Drain(reader); } catch (IOException ex) when (ex.Message == "synthetic pipe failure") { failedRead = true; }
    Require(failedRead);
});
Console.WriteLine($"{passed} PASS / {failed} FAIL");
return failed == 0 ? 0 : 1;

sealed class GeneratedStream(int length, int failAfter = int.MaxValue) : Stream
{
    public int Consumed { get; private set; }
    public override bool CanRead => true; public override bool CanSeek => false; public override bool CanWrite => false;
    public override long Length => length; public override long Position { get => Consumed; set => throw new NotSupportedException(); }
    public override int Read(byte[] buffer, int offset, int count) => Read(buffer.AsSpan(offset, count));
    public override int Read(Span<byte> buffer)
    {
        if (Consumed >= failAfter) throw new IOException("synthetic pipe failure");
        int count = Math.Min(buffer.Length, length - Consumed); buffer[..count].Fill((byte)'x'); Consumed += count; return count;
    }
    public override ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default)
        => ValueTask.FromResult(Read(buffer.Span));
    public override Task<int> ReadAsync(byte[] buffer, int offset, int count, CancellationToken cancellationToken)
        => Task.FromResult(Read(buffer, offset, count));
    public override void Flush() { } public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();
    public override void SetLength(long value) => throw new NotSupportedException(); public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
}
sealed class FragmentedStream(byte[] bytes) : Stream
{
    public int Consumed { get; private set; }
    public override bool CanRead => true; public override bool CanSeek => false; public override bool CanWrite => false;
    public override long Length => bytes.Length; public override long Position { get => Consumed; set => throw new NotSupportedException(); }
    public override int Read(byte[] buffer, int offset, int count) => Read(buffer.AsSpan(offset, count));
    public override int Read(Span<byte> buffer)
    {
        int count = Math.Min(1, Math.Min(buffer.Length, bytes.Length - Consumed)); bytes.AsSpan(Consumed, count).CopyTo(buffer); Consumed += count; return count;
    }
    public override async ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default)
    { await Task.Yield(); return Read(buffer.Span); }
    public override void Flush() { } public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();
    public override void SetLength(long value) => throw new NotSupportedException(); public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
}
