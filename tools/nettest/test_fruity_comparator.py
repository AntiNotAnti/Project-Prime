    def test_native_generation_preserves_malformed_inputs_and_records_full_outputs(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            maps, assets = root / 'maps', root / 'assets/AMHE1'
            maps.mkdir()
            (maps / 'static.json').write_text('{"name":"NCX EMULATED STATIC"}')
            files = list(native.fixture_file_paths(assets, maps))
            for path, kind in files:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(self.native_model(0) if kind == 'Model' else b'original')
            original = native.digest(files[0][0])
            def generate(command, **options):
                self.assertIn('-mapgen', command)
                self.assertNotIn('-headless', command)
                self.assertNotIn('-server', command)
                self.assertEqual(options['env']['FRUITY_NCX_USER_DATA'], str((root / 'native-fixture-preparation').resolve()))
                for path, kind in files:
                    path.write_bytes(self.native_model() if kind == 'Model' else b'generated')
                return SimpleNamespace(returncode=0)
            manifest = {}
            with patch.object(runner.subprocess, 'run', side_effect=generate):
                runner.prepare_native_fixture_data(SimpleNamespace(out=root), native, root / 'binary', maps,
                    [dict(version='AMHE1', privateCopy=str(assets))], f'0.35.1.0\nAMHE1={assets}\n', manifest)
            row = manifest['nativeFixturePreparation']
            self.assertEqual(row['exit'], 0)
            self.assertEqual(len(row['generatedAfter']), 5)
            self.assertEqual(native.digest(Path(row['generatedBefore'][0]['backup'])), original)
            self.assertEqual(row['generatedAfter'][0]['texturePayloads'][0]['imageSize'], 2)

