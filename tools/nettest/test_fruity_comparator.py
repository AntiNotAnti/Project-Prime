    def native_model(self, image_size=2):
        data = bytearray(144)
        struct.pack_into('<H', data, 40, 1)
        struct.pack_into('<I', data, 44, 104)
        struct.pack_into('<BBHHHII', data, 104, 1, 0, 2, 2, 0, 100, image_size)
        return data

